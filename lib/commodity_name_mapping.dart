  /// Search for commodities matching the query
  /// Returns list of matching commodity names, prioritizing prefix matches
  static List<String> searchCommodities(String query) {
    if (query.isEmpty) return [];
    
    final lowerQuery = query.toLowerCase();
    final exactMatches = <String>[];
    final prefixMatches = <String>[];
    final partialMatches = <String>[];

    for (final commodity in _commodityMapping.keys) {
      final lowerCommodity = commodity.toLowerCase();
      
      if (lowerCommodity == lowerQuery) {
        exactMatches.add(commodity);
      } else if (lowerCommodity.startsWith(lowerQuery)) {
        prefixMatches.add(commodity);
      } else if (lowerCommodity.contains(lowerQuery)) {
        partialMatches.add(commodity);
      }
    }

    // Combine and sort results
    final results = [...exactMatches, ...prefixMatches, ...partialMatches];
    return results.take(10).toList(); // Limit to 10 suggestions
  }

  /// Get Urdu name for English commodity name
  static String getUrduName(String englishName) {
    return _commodityMapping[englishName] ?? englishName;
  }

  /// Get all commodities
  static List<String> getAllCommodities() {
    return _commodityMapping.keys.toList();
  }
